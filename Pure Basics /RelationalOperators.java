class RelationalOperators
{
    public static void main(String[] args) {
        int n0 = 13;
        int n1 = 30;
        boolean result = n0 >= n1;

        System.out.print(result);

        /* 
        ===Relational Operators===

        * > < Less-than and Greater-than
        * >= <= Less-than or equal to and Greater-than or equal to
        * == Equivalent to
        * === Identical to 
        * != Not equal to
        * !== Not equivalent to
        * !=== Not identical to

        */
    }
}